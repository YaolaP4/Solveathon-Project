"""Reproduce the plan-alignment tuning in the Field Notes (docs/finals_field_notes.md, section 3.1).

For every live opportunity that the qualifier's AI pipeline had already reviewed (matched by opportunity
number), compare candidate plan-alignment signals and the full score against the qualifier's judgment:

  on topic          = Jev rated the grant's domain relevance "strong" or "moderate"
  relevant and DHHS = on topic AND Jev's applicant role "lead" or "partner"
  (data/results/jev_outputs.csv; an opportunity number listed twice counts once, relevant if either row is)

Plan alignment is judged against "on topic" (it measures topic fit only); the full score, which also
weighs eligibility, against "relevant and DHHS".

Reports AUC and the share of each signal's top 50 that is relevant. These are AI reference labels from the
qualifier, used only for tuning; the honest check is precision@10 on fresh human labels (Evaluation page).

    python src/tune_semantic.py [DATE]     # DATE = a saved raw/{DATE}/grants.json in storage; needs AOAI_* set
Writes docs/tuning_report.md
"""

import sys

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

import config
import matcher
import normalize
from storage import get_store

OUT = config.ROOT / "docs" / "tuning_report.md"


def reference() -> pd.DataFrame:
    raw = pd.read_csv(config.RAW_GRANTS, dtype=str, keep_default_na=False)
    number = raw.set_index("opportunity_id")["opportunity_number"]
    jev = pd.read_csv(config.RESULTS / "jev_outputs.csv", dtype=str)
    jev["opportunity_number"] = jev["grant_id"].map(number)
    jev["on_topic"] = jev["domain_relevance"].isin(["strong", "moderate"])
    jev["relevant"] = jev["on_topic"] & jev["applicant_role"].isin(["lead", "partner"])
    return jev.dropna(subset=["opportunity_number"]).groupby("opportunity_number")[["on_topic", "relevant"]].max().reset_index()


def main(date: str) -> None:
    store, agency = get_store(), config.load_agency()
    raw = store.read_json(f"raw/{date}/grants.json")
    details = {h["id"]: store.read_json(f"details/{h['id']}.json") for h in raw["hits"]}
    live, _ = normalize.normalize(raw["hits"], {k: v for k, v in details.items() if v}, date, agency)
    cfg = matcher.mm_settings(agency)
    docs = matcher.objective_docs(agency)
    texts = [matcher.opportunity_text(r) for _, r in live.iterrows()]
    plan = [d["text"] for d in docs]
    o = matcher.embed_cached(store, texts, print)
    p = matcher.embed_cached(store, plan, print)
    a = matcher.embed_cached(store, cfg["off_topic_anchors"], print)
    sim, off = o @ p.T, (o @ a.T).max(axis=1, keepdims=True)
    tf = matcher.tfidf_similarity(texts, plan)
    cal = cfg["calibration"]
    signals = {
        "Raw embedding similarity": sim.max(axis=1),
        "TF-IDF only": tf.max(axis=1),
        "Embedding margin vs off-topic fields": (sim - off).max(axis=1),
        "Hybrid (shipped)": (0.5 * matcher._lin(sim - off, cal["embedding_margin"]) + 0.5 * matcher._lin(tf, cal["tfidf"])).max(axis=1),
    }
    scored, _ = matcher.score(live, agency, store, print)
    df = live[["opportunity_number"]].copy()
    for k, v in signals.items():
        df[k] = v
    df = df.merge(scored[["opportunity_number", "score"]], on="opportunity_number").rename(columns={"score": "Full five-signal score"})
    df = df.drop_duplicates("opportunity_number")
    m = df.merge(reference(), on="opportunity_number")
    rows = []
    for k in [*signals, "Full five-signal score"]:
        cells = []
        for label in ("on_topic", "relevant"):
            top = m.sort_values(k, ascending=False).head(50)
            cells += [f"{roc_auc_score(m[label], m[k]):.2f}", f"{top[label].mean():.0%}"]
        rows.append(f"| {k} | " + " | ".join(cells) + " |")
    lines = [
        "# Plan-alignment tuning report", "",
        f"Live pull of {date}: {len(live)} open or forecast opportunities. Matched to the qualifier's AI-reviewed set "
        f"(one row per opportunity number): **{len(m)}**; on topic: **{int(m['on_topic'].sum())}**; on topic and DHHS can "
        f"apply: **{int(m['relevant'].sum())}**.", "",
        "| Signal | AUC, on topic | Top 50 on topic | AUC, relevant and DHHS can apply | Top 50 relevant |",
        "|---|---|---|---|---|", *rows, "",
        "Generated by `src/tune_semantic.py`. AI reference labels from the qualifier are used for tuning only; "
        "precision@10 on fresh human labels is on the app's Evaluation page.",
    ]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "2026-11-07")
